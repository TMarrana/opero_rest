@register.simple_tag
def icone(nome, classes="h-5 w-5"):
    """SVG de traço, decorativo (aria-hidden): o texto ao lado diz o que é."""
    desenho = _ICONES.get(nome)
    if desenho is None:
        raise template.TemplateSyntaxError(f"Ícone desconhecido: {nome!r}")
    return format_html(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" class="{}" aria-hidden="true" '
        'focusable="false">{}</svg>',
        classes,
        mark_safe(desenho),
    )


@register.filter
def iniciais(nome):
    """Duas letras para o avatar: a primeira e a última palavra do nome.
    «Marta Silva» → «MS»; um email usa só a primeira letra."""
    texto = str(nome or "").strip()
    if not texto:
        return "?"
    if "@" in texto:
        return texto[0].upper()
    partes = texto.split()
    if len(partes) == 1:
        return partes[0][:2].upper()
    return (partes[0][0] + partes[-1][0]).upper()


@register.simple_tag(takes_context=True)
def url_exportar(context, formato, chave="exportar"):
    """O endereço da página com os mesmos filtros e o formato de exportação
    (Fase 15)."""
    query = context["request"].GET.copy()
    for k in ("exportar", "formato"):
        query.pop(k, None)
    query[chave] = formato
    return "?" + query.urlencode()


@register.inclusion_tag("components/exportar.html", takes_context=True)
def exportar(context, rotulo="Exportar"):
    """Os links CSV e Excel de uma lista, com os filtros do ecrã."""
    return {
        "rotulo": rotulo,
        "url_csv": url_exportar(context, "csv"),
        "url_xlsx": url_exportar(context, "xlsx"),
    }
